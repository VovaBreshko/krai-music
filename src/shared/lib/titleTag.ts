/**
 * Правда, если в названии трека есть серый фрагмент в треугольных скобках
 * («Мы с района <prod. by Black Water>»). Используется контейнерами названий,
 * чтобы красить многоточие в серый (оно наследует цвет контейнера) только
 * тогда, когда в названии реально есть серый фрагмент. Проверка совпадает
 * с разбиением текста в компоненте TrackTitle.
 */
export function hasTitleTag(title: string): boolean {
  return /<[^>]+>/.test(title)
}